#!/usr/bin/env python
"""
Regenerate the entire ``saltext.gsuite`` module surface from Google Discovery + the bundled
``gws`` CLI.

This is a *reconciler*, not an additive scaffolder: each run recomputes the full fileset for
the current CLI/Discovery release and creates, updates, and deletes generated modules, states,
tests, docs, and schema snapshots so the tree matches exactly what the CLI exposes. Hand-tuned
code lives only in ``states/overrides/`` and is never overwritten.

Usage::

    python tools/generate_modules.py --all
    python tools/generate_modules.py --service drive --service gmail
    python tools/generate_modules.py --all --no-cache     # force re-fetch Discovery docs
"""

from __future__ import annotations

import argparse
import json
import os
import pprint
import subprocess
import sys
import textwrap

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from _codegen import discovery  # noqa: E402
from _codegen import helpers as helpers_mod  # noqa: E402
from _codegen import naming  # noqa: E402

try:
    from jinja2 import Environment
    from jinja2 import FileSystemLoader
except ImportError:  # pragma: no cover
    sys.exit("jinja2 is required: pip install jinja2")

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "src", "saltext", "gsuite")
META = os.path.join(SRC, "metadata")
MODULES = os.path.join(SRC, "modules")
STATES = os.path.join(SRC, "states")
OVERRIDES = os.path.join(STATES, "overrides")
SCHEMAS = os.path.join(META, "schemas")
TESTS_M = os.path.join(ROOT, "tests", "unit", "modules")
TESTS_S = os.path.join(ROOT, "tests", "unit", "states")
DOCS_M = os.path.join(ROOT, "docs", "ref", "modules")
DOCS_S = os.path.join(ROOT, "docs", "ref", "states")
MANIFEST = os.path.join(META, "generated_manifest.json")
TEMPLATES = os.path.join(os.path.dirname(os.path.abspath(__file__)), "_codegen", "templates")

HEADER = "# DO NOT EDIT - generated by tools/generate_modules.py. Changes will be overwritten."

_ENV = Environment(
    loader=FileSystemLoader(TEMPLATES),
    keep_trailing_newline=True,
    trim_blocks=False,
    lstrip_blocks=False,
)
_ENV.filters["tojson"] = json.dumps


# --------------------------------------------------------------------------------------------
# helpers
# --------------------------------------------------------------------------------------------
def _rel(path):
    return os.path.relpath(path, ROOT)


def resolve_binary(explicit=None):
    """Locate a gws binary for generation (dev sandbox copy preferred)."""
    if explicit:
        return explicit
    for candidate in (
        os.path.join(ROOT, "sandbox", "gws"),
        os.path.join(SRC, "_vendor", "gws"),
        os.path.join(SRC, "_vendor", "gws.exe"),
    ):
        if os.path.isfile(candidate):
            return candidate
    raise SystemExit("No gws binary found (looked in sandbox/ and _vendor/).")


def load_services():
    with open(os.path.join(META, "services.json"), encoding="utf-8") as handle:
        return json.load(handle)["services"]


def _indent(text, prefix="    "):
    return "\n".join(prefix + line if line else "" for line in text.splitlines())


def _wrap(text, width=88, indent="    "):
    if not text:
        return ""
    return textwrap.fill(
        naming.rst_escape(naming.clean_description(text)),
        width=width,
        initial_indent=indent,
        subsequent_indent=indent,
    )


def _cap(text, limit=200):
    text = naming.clean_description(text)
    if len(text) > limit:
        text = text[: limit - 1].rstrip() + "\N{HORIZONTAL ELLIPSIS}"
    return naming.rst_escape(text)


