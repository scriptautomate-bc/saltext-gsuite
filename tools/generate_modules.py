def build_method_docstring(virtualname, method, required, optional):
    lines = []
    if method.description:
        lines.append(_wrap(method.description))
        lines.append("")
    lines.append(f"    HTTP: ``{method.http_method}``  Discovery: ``{method.dotted}``")
    lines.append("")
    if required:
        lines.append("    Required parameters:")
        lines.append("")
        for param in required:
            lines.append(f"    * ``{param['orig']}`` ({param['type']}): {_cap(param['desc'])}")
        lines.append("")
    if method.has_body:
        lines.append("    * ``body`` (dict): request body payload.")
        lines.append("")
    if method.supports_media_upload:
        lines.append("    * ``upload`` (str): local path of a file to upload as media content.")
        lines.append("")
    if optional:
        lines.append("    Optional parameters (pass via keyword args):")
        lines.append("")
        for param in optional:
            flag = " *(deprecated)*" if param.get("deprecated") else ""
            lines.append(f"    * ``{param['orig']}`` ({param['type']}){flag}: {_cap(param['desc'])}")
        lines.append("")
    example_args = " ".join(f"{p['orig']}=<{p['type']}>" for p in required[:3])
    lines.append("    CLI Example:")
    lines.append("")
    lines.append("    .. code-block:: bash")
    lines.append("")
    lines.append(f"        salt '*' {virtualname}.{method_fn_name(method)} {example_args}".rstrip())
    return "\n".join(lines).rstrip()


def method_fn_name(method):
    return naming.function_name(method.resource_path, method.name)


def build_method_context(virtualname, method):
    required = naming.required_params(method)
    optional = naming.optional_params(method)
    parts = [p["py"] for p in required]
    if method.has_body:
        parts.append("body=None")
    if method.supports_media_upload:
        parts.append("upload=None")
    parts.append("**params")
    return {
        "fn_name": method_fn_name(method),
        "method_name": method.name,
        "signature": ", ".join(parts),
        "required": required,
        "has_body": method.has_body,
        "has_upload": method.supports_media_upload,
        "docstring": build_method_docstring(virtualname, method, required, optional),
    }


def build_helper_docstring(virtualname, helper):
    lines = []
    if helper.description:
        lines.append(_wrap(f"[Helper] {helper.description}"))
        lines.append("")
    if helper.args:
        lines.append("    Positional arguments:")
        lines.append("")
        for arg in helper.args:
            req = "required" if arg.required else "optional"
            lines.append(f"    * ``{arg.py}`` ({req}): {_cap(arg.desc) or arg.name}")
        lines.append("")
    if helper.options:
        lines.append("    Options:")
        lines.append("")
        for opt in helper.options:
            req = "required" if opt.required else "optional"
            kind = "value" if opt.takes_value else "flag"
            lines.append(f"    * ``{opt.py}`` ({req} {kind}): {_cap(opt.desc)}")
        lines.append("")
    lines.append("    CLI Example:")
    lines.append("")
    lines.append("    .. code-block:: bash")
    lines.append("")
    lines.append(f"        salt '*' {virtualname}.{helper.py}")
    return "\n".join(lines).rstrip()


def build_helper_context(virtualname, helper):
    required = [a.py for a in helper.args if a.required]
    required += [o.py for o in helper.options if o.required]
    optional = [a.py for a in helper.args if not a.required]
    optional += [o.py for o in helper.options if not o.required]
    parts = list(required) + [f"{name}=None" for name in optional] + ["test=False"]
    return {
        "fn_name": helper.py,
        "command": helper.command,
        "signature": ", ".join(parts),
        "positionals": [a.py for a in helper.args],
        "positionals_repr": ", ".join(a.py for a in helper.args),
        "flags": [{"long": o.long, "py": o.py} for o in helper.options if o.takes_value],
        "switches": [{"long": o.long, "py": o.py} for o in helper.options if not o.takes_value],
        "docstring": build_helper_docstring(virtualname, helper),
    }


def detect_crud(methods):
    """Group methods by resource and emit state contexts for CRUD-shaped resources."""
    by_resource = {}
    for method in methods:
        by_resource.setdefault(method.resource_path, {})[method.name] = method
    resources = []
    for resource_path in sorted(by_resource):
        names = by_resource[resource_path]
        get = names.get("get")
        create = "create" if "create" in names else ("insert" if "insert" in names else None)
        update = "patch" if "patch" in names else ("update" if "update" in names else None)
        delete = "delete" if "delete" in names else None
        if not (get and create and delete):
            continue
        get_required = naming.required_params(get)
        if not get_required:
            continue
        id_param = get_required[-1]["orig"]
        base = "_".join(naming.snake(p) for p in resource_path)
        resources.append(
            {
                "present_name": f"{base}_present",
                "absent_name": f"{base}_absent",
                "label": resource_path[-1],
                "id_param": id_param,
                "get_fn": naming.function_name(resource_path, get.name),
                "create_fn": naming.function_name(resource_path, create),
                "update_fn": naming.function_name(resource_path, update) if update else None,
                "update_method": update,
                "delete_fn": naming.function_name(resource_path, delete),
            }
        )
    return resources


